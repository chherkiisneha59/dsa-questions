public class striver30 {

    static void larger(int n, int m) {
        if (n > m) {
            System.out.println(n + " " + " is larger");
        } else {
            System.out.println(m + " " + "is larger");
        }
    }

    public static void main(String[] args) {
        larger(4, 5);
        larger(6, 2);
    }
}